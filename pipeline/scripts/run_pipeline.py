"""End-to-end: annual-report PDFs -> a folder a non-programmer can use.

The run produces two kinds of file, and they are kept apart on purpose:

    <workdir>/
      请先看这个.html      <- the verdict, for the person who opens folders
      请先看这个.md        <- the same content, for the agent that reads it
      <公司>_估值模型.xlsm   <- the deliverable
      _AI参考_可删/        <- everything else; an agent may read it, a user may delete it

The card is written twice on purpose. A .md file double-clicked on Windows opens
in Notepad and shows its own markup; .html opens in a browser. The agent reads the
.md, the office user reads the .html, and both are rendered from one model so they
cannot drift apart.

Eleven artifacts used to land side by side, and the first question from an analyst
was always "which one do I open". Nine of them are machinery. The split is not
cosmetic: it is the difference between a folder that explains itself and a folder
that needs a phone call.
"""
import argparse
import hashlib
import io
import json
import os
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
SKILL = os.path.dirname(HERE)

# The folder a user may delete. Named for what it is -- reference material for an
# agent, not something they have to keep. Everything in it is either regenerated by
# the next run or duplicated on the card, so "可删" is a promise, not a hint; the
# leading "_" also sorts it below the two files that matter.
RAW = "_AI参考_可删"
CARD = "请先看这个"
NOTE = "交付说明.md"
ACCEPT = "验收报告.md"
TOTAL = 11


LOG = None


def run(cmd, verbose=False):
    # The raw command line is noise to the person this skill is for, and every
    # stage prints its own findings. Show the command only on --verbose, where the
    # reader is debugging rather than deciding.
    if verbose:
        print("\n$ " + " ".join(str(c) for c in cmd))
    if LOG is None:
        return subprocess.run([str(c) for c in cmd]).returncode
    # The transcript is the run's own business, not the caller's: a stage that
    # dies at step 9 is exactly when the log is worth having, and asking whoever
    # launched it to capture stdout means it is missing precisely then. Children
    # are told to emit UTF-8 so a Chinese path or a Chinese finding survives the
    # pipe on any console.
    env = dict(os.environ, PYTHONIOENCODING="utf-8")
    p = subprocess.Popen([str(c) for c in cmd], stdout=subprocess.PIPE,
                         stderr=subprocess.STDOUT, env=env)
    for line in p.stdout:
        text = line.decode("utf-8", "replace")
        sys.stdout.write(text)
        LOG.write(text)
    p.wait()
    LOG.flush()
    return p.returncode


def banner(step, text, minutes=None):
    print("\n" + "-" * 64)
    tail = "" if minutes is None else "（约 %s）" % minutes
    print("第 %d/%d 步：%s%s" % (step, TOTAL, text, tail))
    print("-" * 64, flush=True)



def has_excel():
    """这个后端背后有没有真的 Excel。纯 Python 后端没有，公式值交给办公人员
    打开文件时算（workbook.xml 里已经打了 fullCalcOnLoad=1）。"""
    sys.path.insert(0, HERE)
    import com_excel
    return com_excel.HAS_EXCEL


def default_cache_dir():
    """Where parsed PDFs are kept between runs.

    Not inside the run folder: the run folder is named after the period and the
    minute, so a re-run with a new period -- or a user who deleted _AI参考_可删/ --
    would re-parse the same 200-page PDFs for nothing. Parsing is 90% of the wall
    clock (160 s of a 165 s run), and the keys are content-addressed (PDF bytes +
    period + hashes of the parser and the page config), so a stale entry cannot be
    served after a code or config change.

    Outside the skill directory, because what is cached is a company's financial
    statements and the skill directory is shared. Windows 用 %LOCALAPPDATA%，
    Linux / macOS 用 $XDG_CACHE_HOME（缺省 ~/.cache）—— 服务端要能部署到
    Linux，路径就不能只有 Windows 那一个来源。
    """
    local = os.environ.get("LOCALAPPDATA")
    if local and os.path.isdir(local):
        return os.path.join(local, "a-share-valuation-fill", "cache")
    base = os.environ.get("XDG_CACHE_HOME") or os.path.join(
        os.path.expanduser("~"), ".cache")
    return os.path.join(base, "a-share-valuation-fill", "cache")


def code_fingerprints():
    """sha256 (first 8) of the files that decide what a run produces.

    A hand-written version number is a label; this is evidence. When a defect is
    found later, these are what say which deliverables came from the affected code
    -- and unlike a version string they cannot be forgotten during a commit.
    """
    out = {}
    for rel in ("VERSION", "config/mapping.json", "config/pdf_pages.json",
                "config/mapping_quarterly.json",
                "scripts/parse_pdf.py", "scripts/quarterly.py",
                "scripts/write_model.py", "scripts/report.py",
                "scripts/human_card.py"):
        full = os.path.join(SKILL, rel)
        try:
            with open(full, "rb") as fh:
                out[rel] = hashlib.sha256(fh.read()).hexdigest()[:8]
        except OSError:
            continue
    return out


def read_version():
    """The skill's own version, for the output folder name and the manifest.

    A hand-written number drifts the moment someone edits the code and forgets to
    bump it, so it is a label, not a proof -- the per-file fingerprints recorded in
    readback.json are what a later investigation should trust.
    """
    try:
        return io.open(os.path.join(SKILL, "VERSION"), encoding="utf-8").read().strip() or "0"
    except Exception:
        return "0"


def write_card(stem, md, html_text):
    """The human card, both formats, side by side. Called on every exit path."""
    io.open(stem + ".md", "w", encoding="utf-8", newline="\n").write(md)
    io.open(stem + ".html", "w", encoding="utf-8", newline="\n").write(html_text)


def build_blocked_card(pre, params_path, version=None):
    """The one file the user was told to open, written even when nothing ran.

    A blocked preflight has no compat.json and no gaps.json, so the usual summary
    cannot be produced. Saying nothing would leave a folder with no explanation.
    """
    try:
        company = json.load(io.open(params_path, encoding="utf-8")).get("company", {})
    except Exception:
        company = {}
    L = ["# %s（%s）—— 没有生成估值文件" % (company.get("name", "-"),
                                            company.get("code", "-")), ""]
    L.append("**这批 PDF 没有被使用，因为有几份文件对不上。**")
    L.append("")
    L.append("模型是按报告期往表里写数的。一份「第一季度报告」如果被当成年度报告，")
    L.append("它三个月的数字就会写进年度那一列，整个估值建立在三个月的数据上，")
    L.append("而工作簿不会报任何错。所以这里选择停下，而不是猜一个。")
    L.append("")
    L.append("## 需要你处理的问题")
    L.append("")
    for b in pre.get("blocking", []):
        L.append("- **%s**：%s" % (os.path.basename(b.get("pdf") or "-"), b.get("why")))
    L.append("")
    L.append("## 这批文件分别是什么")
    L.append("")
    L.append("| 文件 | 报告类型 | 报告期 |")
    L.append("|---|---|---|")
    for r in pre.get("reports", []):
        L.append("| %s | %s | %s |" % (os.path.basename(r.get("pdf") or "-"),
                                       r.get("kind_cn") or "认不出", r.get("period") or "-"))
    L.append("")
    L.append("改好之后重跑一次即可。")
    model = {
        "title": "%s（%s）—— 没有生成估值文件" % (company.get("name", "-"),
                                                  company.get("code", "-")),
        "headline": "这批 PDF 没有被使用，因为有几份文件对不上。",
        "notes": ["模型是按报告期往表里写数的。一份「第一季度报告」如果被当成年度报告，"
                  "它三个月的数字就会写进年度那一列，整个估值建立在三个月的数据上，"
                  "而工作簿不会报任何错。所以这里选择停下，而不是猜一个。"],
        "period": "-", "valuation_date": "-", "verdict": "blocked",
        "transcribe": ["这批 PDF 没有被使用，因为有几份文件对不上。",
                       "需要处理的问题：%s" % "；".join(
                           "%s：%s" % (os.path.basename(b.get("pdf") or "-"), b.get("why"))
                           for b in pre.get("blocking", []))],
        "years": [],
        "problems": ["%s：%s" % (os.path.basename(b.get("pdf") or "-"), b.get("why"))
                     for b in pre.get("blocking", [])],
        "company": [], "manual": [],
        "reports": [(os.path.basename(r.get("pdf") or "-"),
                     "%s %s" % (r.get("kind_cn") or "认不出", r.get("period") or "-"))
                    for r in pre.get("reports", [])],
        "interim": [],
        "verified": None, "version": version, "blocked": True,
    }
    import human_card
    return human_card.to_markdown(model), human_card.to_html(model)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--params", help="run parameters JSON")
    ap.add_argument("--params-xlsx", help="参数表(.xlsx)，与 --params 二选一")
    ap.add_argument("--reports-dir", help="参数表里相对文件名解析用的目录")
    ap.add_argument("--template", required=True, help="original template .xlsm")
    ap.add_argument("--workdir", required=True)
    ap.add_argument("--clean-template", help="reuse an existing clean template")
    ap.add_argument("--skip-reset", action="store_true")
    ap.add_argument("--name", help="human-readable base name for the delivered workbook")
    ap.add_argument("--no-accept", action="store_true",
                    help="skip the final acceptance check (it is on by default)")
    ap.add_argument("--cache-dir", help="reuse parsed PDFs from here across runs "
                                        "(default: 用户缓存目录/a-share-valuation-fill/cache)")
    ap.add_argument("--clear-cache", action="store_true",
                    help="delete the parse cache before running")
    ap.add_argument("--verbose", action="store_true", help="echo every subprocess command")
    ap.add_argument("--allow-no-annual", action="store_true",
                    help="即使一份年报都没有也继续跑：年度数据留空，"
                         "季报/半年报仍填进报告期历史数据。默认关闭")
    a = ap.parse_args()
    if bool(a.params) == bool(a.params_xlsx):
        ap.error("--params 与 --params-xlsx 必须给且只给一个")
    t0 = time.time()
    os.makedirs(a.workdir, exist_ok=True)
    raw = os.path.join(a.workdir, RAW)
    os.makedirs(raw, exist_ok=True)
    cfg = os.path.join(SKILL, "config")
    py = sys.executable
    version = read_version()

    global LOG
    LOG = io.open(os.path.join(raw, "run.log"), "w", encoding="utf-8", newline="")
    import atexit
    atexit.register(LOG.close)

    # 参数表是给人的输入面，params.json 是给机器的。转换在这里做，调用者不必
    # 先跑一个转换脚本，也就不必自己写驱动。
    if a.params_xlsx:
        sys.path.insert(0, HERE)
        import params_xlsx
        a.params = os.path.join(raw, "params.json")
        json.dump(params_xlsx.read_params(a.params_xlsx, a.reports_dir),
                  io.open(a.params, "w", encoding="utf-8"),
                  ensure_ascii=False, indent=1)
        print("参数表 %s -> %s" % (os.path.basename(a.params_xlsx), a.params))

    def p(name):
        """An intermediate artifact. Lives under _AI参考_可删/."""
        return os.path.join(raw, name)

    def d(name):
        """A deliverable. Lives at the top of the workdir, where a human looks."""
        return os.path.join(a.workdir, name)

    # Parsing is 90% of the wall clock (160 s of a 165 s run) and the same PDFs get
    # re-read on every re-run, so the cache outlives the run folder. Falls back to
    # the run folder when there is no %LOCALAPPDATA%, which is the old behaviour and
    # still correct.
    cache_dir = a.cache_dir or default_cache_dir() or p("_cache")
    if a.clear_cache and os.path.isdir(cache_dir):
        import shutil
        shutil.rmtree(cache_dir, ignore_errors=True)
        print("缓存已清空：%s" % cache_dir)

    def summary_only():
        # The plain-language verdict must reach the user even when the run stops
        # early: that is exactly when they need to know why there is no workbook.
        # It is also written to 请先看这个.md, so a failed run still leaves the one
        # file the user was told to open.
        cmd = [py, os.path.join(HERE, "report.py"),
               "--params", p("params.resolved.json"),
               "--cleanup", os.path.join(cfg, "cleanup.json"),
               "--out-card", d(CARD),
               "--version", version,
               "--summary-only"]
        # A run that stopped before those stages has no compat/gaps to hand over;
        # passing a path that does not exist turns a clear stop into a traceback.
        for flag, name in (("--compat", "compat.json"), ("--gaps", "gaps.json")):
            if os.path.exists(p(name)):
                cmd += [flag, p(name)]
        run(cmd, a.verbose)

    params = json.load(open(a.params, encoding="utf-8"))
    params["_pdf_sha"] = {r["pdf"]: hashlib.sha256(open(r["pdf"], "rb").read()).hexdigest()[:16]
                          for r in params.get("reports", []) if os.path.exists(r["pdf"])}
    params["_mapping_version"] = json.load(open(os.path.join(cfg, "mapping.json"),
                                                encoding="utf-8"))["version"]
    params["_skill_version"] = version
    params["_fingerprints"] = code_fingerprints()
    json.dump(params, open(p("params.resolved.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)

    # ---- 1. what are these documents? ----------------------------------
    # Asked before anything expensive, and before anything is written. The
    # document decides its own period: a report whose cover says 「第一季度报告」
    # never reaches 年度数据, whatever the params claim, because a quarter
    # averaged into a year produces a workbook that looks finished and is not.
    banner(1, "认料与排期：这批 PDF 是什么、能填哪几列", "5 秒")
    if run([py, os.path.join(HERE, "detect.py"),
            "--params", p("params.resolved.json"),
            "--out", p("preflight.json"),
            "--out-report", p("preflight.md")], a.verbose) != 0:
        return 1
    pre = json.load(open(p("preflight.json"), encoding="utf-8"))
    if pre["blocked"]:
        _md, _html = build_blocked_card(pre, a.params, version)
        write_card(d(CARD), _md, _html)
        print("")
        print("=" * 64)
        print("停下：有的文件认不出来，或参数里的报告期与封面不符。")
        print("=" * 64)
        for b in pre["blocking"]:
            print("  - %s" % b["why"])
        print("")
        print("  没有生成任何文件：按错的报告期写数会静默污染估值。")
        print("  逐份文件的判定见 %s" % p("preflight.md"))
        print("  修正办法：改正参数里的 period，或换一份能认出的 PDF。")
        print("  结论已写入 %s" % d(CARD))
        print("=" * 64)
        return 1

    annual = [{"pdf": r["pdf"], "period": r["period"], "kind": r["kind"]}
              for r in pre["usable_annual"]]
    if not annual:
        # 默认停下：没有年报就没有年度数据，估值无从谈起，早停比交出一份
        # 全是空的估值好。--allow-no-annual 是给「我只想先要季度表」的场景，
        # 显式打开才继续，且年度列会整片留空。
        if not a.allow_no_annual:
            print("\n停下：这批文件里没有一份年报，年度数据无从填起。")
            print("  如果只是想把季报/半年报填进「报告期历史数据」，加 --allow-no-annual。")
            return 1
        print("\n注意：没有年报，年度数据将整片留空，只有季报/半年报进「报告期历史数据」。")
    params["reports"] = annual
    # The non-annual reports are not thrown away: 年度数据 takes year-ends only,
    # but 报告期历史数据 is a quarter-granularity sheet and is exactly where a
    # 季报/半年报 belongs. They travel separately so nothing can average a
    # quarter into a year by accident.
    params["reports_interim"] = [{"pdf": r["pdf"], "period": r["period"],
                                  "kind": r["kind"]} for r in pre["excluded"]]
    params["_excluded_reports"] = pre["excluded"]
    params["_preflight"] = {"reports": pre["reports"]}
    json.dump(params, open(p("params.resolved.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)

    clean = a.clean_template or d("clean_template.xlsm")
    if not a.skip_reset:
        banner(2, "清理模板：把样板公司的数据清掉，保留公式", "20 秒")
        cmd = [py, os.path.join(HERE, "reset_template.py"),
               "--template", a.template,
               "--cleanup", os.path.join(cfg, "cleanup.json"),
               "--mapping", os.path.join(cfg, "mapping.json"),
               "--out", clean]
        if params.get("allow_template_mismatch"):
            cmd.append("--allow-template-mismatch")
        if run(cmd, a.verbose) != 0:
            return 1
    else:
        banner(2, "清理模板：已跳过（--skip-reset）")

    banner(3, "读取年报 PDF：这一步最慢，请等待", "1-3 分钟")
    if run([py, os.path.join(HERE, "parse_pdf.py"),
            "--params", p("params.resolved.json"),
            "--pages-config", os.path.join(cfg, "pdf_pages.json"),
            "--cache-dir", cache_dir,
            "--out", p("extract.json")], a.verbose) != 0:
        return 1

    banner(4, "把报表科目对到模板行号", "10 秒")
    if run([py, os.path.join(HERE, "map_fields.py"),
            "--extract", p("extract.json"),
            "--mapping", os.path.join(cfg, "mapping.json"),
            "--params", p("params.resolved.json"),
            "--out", p("fieldmap.json")], a.verbose) != 0:
        return 1

    banner(5, "季度通道：季报/半年报填进报告期历史数据", "5 秒")
    if run([py, os.path.join(HERE, "quarterly.py"),
            "--extract", p("extract.json"),
            "--mapping", os.path.join(cfg, "mapping_quarterly.json"),
            "--out", p("quarterly.json")], a.verbose) != 0:
        return 1

    banner(6, "判断数据够不够用", "5 秒")
    if run([py, os.path.join(HERE, "compat.py"),
            "--fieldmap", p("fieldmap.json"),
            "--mapping", os.path.join(cfg, "mapping.json"),
            "--deps", os.path.join(cfg, "assumption_deps.json"),
            "--out", p("compat.json"),
            "--out-report", p("compat.md")], a.verbose) != 0:
        return 1

    # The gap list is written before validation on purpose: if validation
    # aborts there is no card, and "what to go get next" is the one thing the
    # caller still needs.
    banner(7, "列出还差什么", "5 秒")
    if run([py, os.path.join(HERE, "gaps.py"),
            "--params", p("params.resolved.json"),
            "--fieldmap", p("fieldmap.json"),
            "--compat", p("compat.json"),
            "--cleanup", os.path.join(cfg, "cleanup.json"),
            "--inputs", os.path.join(cfg, "analyst_inputs.json"),
            "--out", p("gaps.json"),
            "--out-report", p("gaps.md")], a.verbose) != 0:
        return 1

    banner(8, "写入前校验：会计恒等式与逐项对账", "5 秒")
    if run([py, os.path.join(HERE, "validate.py"),
            "--fieldmap", p("fieldmap.json"),
            "--assertions", os.path.join(cfg, "assertions.json"),
            "--out", p("validate_pre.json")], a.verbose) != 0:
        print("\n停止：写入前校验未通过，没有生成估值文件。")
        summary_only()
        return 1

    banner(9, "写入模型并重算", "30 秒")
    wcmd = [py, os.path.join(HERE, "write_model.py"),
            "--workbook", clean,
            "--fieldmap", p("fieldmap.json"),
            "--params", p("params.resolved.json"),
            "--assertions", os.path.join(cfg, "assertions.json"),
            "--compat", p("compat.json"),
            "--pristine-template", a.template,
            "--analyst-inputs", os.path.join(cfg, "analyst_inputs.json"),
            "--quarterly", p("quarterly.json"),
            "--out", p("readback.json")]
    if a.name:
        wcmd += ["--name", a.name]
    rc = run(wcmd, a.verbose)
    verdict = json.load(open(p("compat.json"), encoding="utf-8"))["verdict"]
    wrote = os.path.exists(p("readback.json"))
    if rc != 0 and not wrote:
        # Three outcomes look alike from an exit code and mean different things:
        # refused (data not good enough), aborted (writer broke something), and
        # written-but-invalid (assertions caught damage the caller accepted).
        if verdict == "facts_only":
            print("\n拒绝写入：判定为「只出事实层」，未生成估值文件。")
            print("  现在可用：%s/ 里的 extract.json、fieldmap.json、compat.md、gaps.md。" % RAW)
            print("  gaps.md 写了还差什么、补上了能解锁什么。")
        else:
            print("\n中止：写入后校验未通过，没有生成可用的估值文件。")
        summary_only()
        return 1
    if rc != 0:
        print("\n注意：文件已写出，但写入后断言未通过。")
        print("      它不是一份可用的估值，下面的报告会说明原因。")

    model_path = None
    if wrote:
        model_path = json.load(open(p("readback.json"), encoding="utf-8")).get("workbook")

    banner(10, "生成给人看的结论与交付说明", "3 秒")
    if run([py, os.path.join(HERE, "report.py"),
            "--params", p("params.resolved.json"),
            "--readback", p("readback.json"),
            "--validate-pre", p("validate_pre.json"),
            "--compat", p("compat.json"),
            "--gaps", p("gaps.json"),
            "--cleanup", os.path.join(cfg, "cleanup.json"),
            "--out-card", d(CARD),
            "--out-card-html", d(CARD) + ".html",
            "--out-manifest", p("manifest.md"),
            "--out-note", p(NOTE),
            "--version", version], a.verbose) != 0:
        return 1
    # A workbook that was written but failed an assertion is still the file the
    # caller asked for (allow_incomplete_history is an explicit opt-in), and the
    # verdict already announced why. Returning here would skip the acceptance
    # check and the closing summary -- which is precisely the run where the user
    # most needs to be told what they are holding.
    wrote_failed = rc != 0

    accept_ok = None
    if not a.no_accept and model_path:
        banner(11, "验收：确认产出还是原件那台引擎", "15 秒")
        acc = [py, os.path.join(HERE, "acceptance.py"),
               "--pristine", a.template,
               "--output", model_path,
               "--out", p("acceptance.json"),
               "--out-report", p(ACCEPT)]
        if has_excel():
            # 「同数据同结果」要拿两个工作簿在 Excel 里各算一遍再比，只有真的
            # 驱动 Excel 的后端做得到；做不到就不传这个开关，让验收报告写明
            # 是「没做」，而不是含糊地算过。
            acc.insert(4, "--equivalence")
        accept_ok = run(acc, a.verbose) == 0
    else:
        banner(11, "验收：已跳过")

    print("\n" + "=" * 64)
    print("完成。需要看的文件都在：%s" % a.workdir)
    print("=" * 64)
    print("  %-16s 这份文件能不能用，一句话结论（双击这个）" % (CARD + ".html"))
    print("  %-16s 同一份内容，给 AI 读的" % (CARD + ".md"))
    if model_path:
        print("  %-16s 模型本体" % os.path.basename(model_path))
    print("  %-16s 运行日志，排查时才看" % (RAW + "/run.log"))
    print("  %-16s 其它文件都在这里，不用管" % (RAW + "/"))
    print("=" * 64)
    if model_path and not has_excel():
        print("这份 .xlsm 的公式缓存是空的：用 Excel 打开时它会自己重算一遍")
        print("（文件里已写 fullCalcOnLoad=1），算出来的数就是最终结果。")
    print("耗时 %.0f 秒。判定：%s" % (time.time() - t0, verdict))

    # Exit codes, because three outcomes look identical from a shell:
    #   0  done -- the file the card describes is on disk
    #   1  stopped -- nothing usable was produced (blocked, refused, validation)
    #   2  written, but a check the verdict did NOT predict failed
    # A facts_only run with allow_incomplete_history is the first case: the caller
    # asked for the facts despite the gap, the verdict and the filename announce
    # the gap, and derived_nonzero fails as a direct consequence of it. Returning
    # 1 there makes every accepted-degraded run look broken -- which is how a real
    # failure ends up ignored.
    predicted = (verdict == "facts_only"
                 and bool(params.get("allow_incomplete_history")))
    if wrote_failed:
        if predicted:
            print("\n写入后断言未通过，但这是「只出事实层 + 允许历史不完整」的必然结果，"
                  "\n      判定已写在卡片第一行。退出码 0。")
        else:
            print("\n注意：第 9 步的写入后断言未通过，且判定并未预期这一点。"
                  "\n      这份文件不是可用的估值，仅供核对事实。退出码 2。")
    if accept_ok is False:
        print("\n验收未通过：这份产出与原件不一致，请先看 %s。退出码 2。" % ACCEPT)
    if accept_ok is False or (wrote_failed and not predicted):
        return 2
    return 0


